#!/usr/bin/env bash
# Builds the MeoSQL integration's test and example in debug and release, runs
# the test in both modes, runs the example for a few seconds and checks its SVG.
# Prints PASS or FAIL.
#
# Env: METTLE (compiler, default ../Mettle/bin/mettle next to this repo),
#      MEOSQL_DIR (MeoSQL checkout, default ../meosql), RUN_FOR (default 3).
#
# The compiler resolves `import "meosql/..."` through the mettle.deps nearest
# to the importing file, ahead of any -I directory. To build against
# MEOSQL_DIR, the integration is copied into $OUT/stage next to a generated
# mettle.deps that maps meosql= to it.

set -u
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT" || exit 1
METTLE="${METTLE:-$ROOT/../Mettle/bin/mettle}"
MEOSQL_DIR="${MEOSQL_DIR:-$ROOT/../meosql}"
RUN_FOR="${RUN_FOR:-3}"
OUT="build/integrations/meosql"
STAGE="$OUT/stage"
mkdir -p "$OUT"

if [ ! -f "$MEOSQL_DIR/src/feed/feed.mettle" ]; then
  echo "FAIL  MEOSQL_DIR=$MEOSQL_DIR has no src/feed/feed.mettle"
  echo "FAIL"
  exit 1
fi
MEOSQL_ABS="$(cd "$MEOSQL_DIR" && pwd)"
MEOSQL_REV="$(git -C "$MEOSQL_ABS" rev-parse --short HEAD 2>/dev/null || echo 'no git')"
echo "meosql: $MEOSQL_ABS ($MEOSQL_REV)"

rm -rf "$STAGE"
mkdir -p "$STAGE"
cp integrations/meosql/mp_meo.mettle "$STAGE/"
cp -r integrations/meosql/tests integrations/meosql/examples "$STAGE/"
cat > "$STAGE/mettle.deps" <<DEPS
# generated by integrations/meosql/build.sh
mistplot=$ROOT/src
meosql=$MEOSQL_ABS
DEPS

fails=0
step() { # name, command...
  local name="$1"; shift
  if "$@" > "$OUT/$name.log" 2>&1; then
    echo "ok    $name"
  else
    echo "FAIL  $name (see $OUT/$name.log)"
    tail -n 5 "$OUT/$name.log" | sed 's/^/      /'
    fails=$((fails + 1))
  fi
}

# One polyline per series (3), the "updated hh:mm:ss · commit N" subtitle, and
# points that changed between the first and the final snapshot.
check_svg() { # mode
  local svg="$OUT/live.$1.svg" first="$OUT/live.$1.first.svg"
  [ -s "$svg" ] && [ -s "$first" ] || { echo "missing $svg or $first"; return 1; }
  local polys; polys="$(grep -o '<polyline' "$svg" | wc -l)"
  echo "polylines: $polys"
  [ "$polys" = 3 ] || return 1
  grep -Eo 'updated [0-9]{2}:[0-9]{2}:[0-9]{2} · commit [0-9]+' "$svg" || return 1
  if cmp -s <(grep -o 'points="[^"]*"' "$first") <(grep -o 'points="[^"]*"' "$svg"); then
    echo "polyline points did not change between the two snapshots"
    return 1
  fi
}

for mode in debug release; do
  flag=""
  [ "$mode" = release ] && flag="--release"
  step "build-test-$mode" "$METTLE" $flag --build \
    "$STAGE/tests/meosql_test.mettle" -o "$OUT/meosql_test.$mode"
  step "build-example-$mode" "$METTLE" $flag --build \
    "$STAGE/examples/meo_live_chart.mettle" -o "$OUT/meo_live_chart.$mode"
  if [ -x "$OUT/meosql_test.$mode" ]; then
    step "run-test-$mode" "$OUT/meosql_test.$mode"
    echo "      $(tail -n 1 "$OUT/run-test-$mode.log")"
  fi
  if [ -x "$OUT/meo_live_chart.$mode" ]; then
    step "run-example-$mode" "$OUT/meo_live_chart.$mode" --run-for "$RUN_FOR" \
      --db "$OUT/live.$mode.db" --svg "$OUT/live.$mode.svg" \
      --first-svg "$OUT/live.$mode.first.svg" --quiet
    echo "      $(tail -n 1 "$OUT/run-example-$mode.log")"
    step "check-svg-$mode" check_svg "$mode"
  fi
done

if [ "$fails" = 0 ]; then
  echo "PASS"
  exit 0
fi
echo "FAIL ($fails step(s))"
exit 1
